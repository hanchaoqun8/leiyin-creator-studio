  /** 关键词权重匹配（简单可解释的检索，不依赖向量库） */
  function score(text, query) {
    let s = 0;
    const q = String(query || '');
    const tags = text.tags || [];
    tags.forEach((t) => {
      if (q.includes(t)) s += 3;
      else {
        // 单字级弱匹配
        for (const ch of t) {
          if (ch.length === 1 && q.includes(ch)) s += 0.15;
        }
      }
    });
    return s;
  }

  /**
   * 检索知识片段
   * @param {string[]} cultureKeys 勾选的文化键（来自 options.CULTURES）
   * @param {string} topic 主题文本（含自定义）
   * @param {number} perLib 每个库最多取几条
   */
  function retrieve(cultureKeys, topic, perLib, optionsLib) {
    perLib = perLib || 2;
    const opts = optionsLib || (typeof require === 'function'
      ? require('./options')
      : (typeof globalThis !== 'undefined' ? globalThis : self).LEIYIN_OPTIONS);
    const keys = new Set();
    (cultureKeys || []).forEach((k) => {
      const c = opts.CULTURES.find((x) => x.key === k);
      if (c) (c.kb || []).forEach((lib) => keys.add(lib));
    });
    // 兜底：没勾任何文化项时，至少给专业双库
    if (!keys.size) { keys.add('meridian'); keys.add('leiyin'); }

    const out = [];
    keys.forEach((libKey) => {
      const lib = LIBRARIES[libKey];
      if (!lib) return;
      const ranked = lib.items
        .map((it) => ({ it, s: score(it, topic) }))
        .sort((a, b) => b.s - a.s);
      ranked.slice(0, perLib).forEach(({ it }) => {
        out.push({ library: lib.label, id: it.id, text: it.text });
      });
    });
    return out;
  }

